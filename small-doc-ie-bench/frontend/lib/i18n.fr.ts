/** A small set of UI messages contain user/model names and cannot be exact keys. */
export function translateFrenchPattern(message: string): string | undefined {
  const patterns: Array<[RegExp, (...matches: string[]) => string]> = [
    [/^Agent (.+) deleted$/, (name) => `Agent ${name} supprimé`],
    [/^Agent (.+) updated$/, (name) => `Agent ${name} mis à jour`],
    [/^Profile (.+) deleted$/, (name) => `Profil ${name} supprimé`],
    [/^Download failed: (.+)$/, (name) => `Échec du téléchargement : ${name}`],
    [/^No (.+) tasks\.$/, (status) => `Aucune tâche ${FR_MESSAGES[status] ?? status}.`],
  ];
  for (const [pattern, format] of patterns) {
    const match = message.match(pattern);
    if (match) return format(...match.slice(1));
  }
  return undefined;
}
